import { readFile, writeFile } from "node:fs/promises";

import { makeBuilderConfig, validateForkConfig } from "./fork-config.mjs";

const root = new URL("../", import.meta.url);
const json = (value) => JSON.stringify(value, null, 2) + "\n";
const readJson = async (file) => JSON.parse(await readFile(new URL(file, root), "utf8"));

async function configure() {
  const config = await readJson("fork.config.json");
  const validation = validateForkConfig(config);
  if (!validation.ok) throw new Error(validation.errors.join("\n"));
  const pkg = await readJson("src/main/package.json");
  pkg.version = config.version;
  pkg.productName = config.productName;
  pkg.description = config.description;
  pkg.author = config.maintainer;
  pkg.contributors = [
    "Black Tree Gaming Ltd. and Vortex contributors (upstream)",
    config.maintainer,
  ];
  const workspace = await readJson("package.json");
  workspace.author = config.maintainer;
  workspace.license = pkg.license;
  workspace.contributors = pkg.contributors;
  const builder = makeBuilderConfig(
    await readJson("src/main/electron-builder.config.json"),
    config,
  );
  const generated =
    "// Generated by scripts/configure-fork.mjs. Edit fork.config.json instead.\n" +
    `export const FORK = ${JSON.stringify(config, null, 2)} as const;\n`;
  await writeFile(new URL("src/main/package.json", root), json(pkg));
  await writeFile(new URL("package.json", root), json(workspace));
  await writeFile(new URL("src/main/electron-builder.config.json", root), json(builder));
  await writeFile(new URL("src/shared/src/fork.ts", root), generated);
  await writeFile(new URL("src/main/fork.config.json", root), json(config));
  console.log(
    `Configured ${config.productName} ${config.version}; automatic updates: ${config.updates.enabled}`,
  );
}

configure().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
